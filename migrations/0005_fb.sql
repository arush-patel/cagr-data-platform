-- ---------------------------------------------------------------------------------------------
-- Labels: a fourth tier. Labels may read anything; nothing but another label may read a label,
-- and every label feature is marked as using later sessions.
-- ---------------------------------------------------------------------------------------------
ALTER TABLE fb.family DROP CONSTRAINT family_tier_check,
    ADD CONSTRAINT family_tier_check CHECK (tier IN ('ind','feat','sig','lbl'));
ALTER TABLE fb.family_timeframe DROP CONSTRAINT family_timeframe_schema_name_check,
    ADD CONSTRAINT family_timeframe_schema_name_check CHECK (schema_name IN ('ind','feat','sig','lbl'));
CREATE OR REPLACE FUNCTION fb.check_family_tiers() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    rank_of CONSTANT jsonb := '{"ind":1,"feat":2,"sig":3,"lbl":4}';
    bad text;
BEGIN
    SELECT string_agg(d.family || ' (' || d.tier || ')', ', ') INTO bad
    FROM unnest(NEW.depends_on) dep
    JOIN fb.family d ON d.family = dep
    WHERE (rank_of ->> d.tier)::int > (rank_of ->> NEW.tier)::int;
    IF bad IS NOT NULL THEN
        RAISE EXCEPTION 'family % (tier %) cannot depend on higher tier: %', NEW.family, NEW.tier, bad;
    END IF;
    IF EXISTS (SELECT 1 FROM unnest(NEW.depends_on) dep WHERE NOT EXISTS (SELECT 1 FROM fb.family WHERE family = dep)
               AND dep <> NEW.family) THEN
        RAISE EXCEPTION 'family % depends on an unregistered family', NEW.family;
    END IF;
    RETURN NEW;
END $$;

CREATE FUNCTION fb.check_label_future() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT NEW.uses_future AND EXISTS (SELECT 1 FROM fb.family WHERE family = NEW.family AND tier = 'lbl') THEN
        RAISE EXCEPTION 'label % must be marked uses_future', NEW.feature;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER feature_def_label_future BEFORE INSERT OR UPDATE ON fb.feature_def
    FOR EACH ROW EXECUTE FUNCTION fb.check_label_future();

-- ---------------------------------------------------------------------------------------------
-- Snapshots: a named, immutable set of builds. Every dataset, tree, model and Observatory run
-- records one, so it can be rerun exactly after newer builds arrive.
-- ---------------------------------------------------------------------------------------------
ALTER TABLE fb.build ADD COLUMN lake_path text;   -- immutable folder, e.g. features/rsi_14/v1/build=<id>/
CREATE TABLE fb.snapshot (
    snapshot_id     text PRIMARY KEY,               -- 'snap-2026-10-15-a1b2c3'
    manifest_hash   text NOT NULL UNIQUE,           -- hash of the sorted build ids: same data, same snapshot
    purpose         text,                           -- 'tree: C1 goldens', 'Observatory run 7f3a'
    created_by      text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE fb.snapshot_build (
    snapshot_id     text NOT NULL REFERENCES fb.snapshot (snapshot_id),
    build_id        text NOT NULL REFERENCES fb.build (build_id),
    PRIMARY KEY (snapshot_id, build_id)
);
CREATE INDEX snapshot_build_build_idx ON fb.snapshot_build (build_id);
CREATE FUNCTION fb.protect_snapshotted_build() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM fb.snapshot_build WHERE build_id = OLD.build_id)
       AND (TG_OP = 'DELETE' OR NEW.lake_path IS DISTINCT FROM OLD.lake_path
            OR NEW.rows_written IS DISTINCT FROM OLD.rows_written) THEN
        RAISE EXCEPTION 'build % is part of a snapshot and cannot change', OLD.build_id;
    END IF;
    RETURN COALESCE(NEW, OLD);
END $$;
CREATE TRIGGER build_snapshot_guard BEFORE UPDATE OR DELETE ON fb.build
    FOR EACH ROW EXECUTE FUNCTION fb.protect_snapshotted_build();
