CREATE TABLE fb.dirty_consumed (
    dirty_id        bigint NOT NULL REFERENCES clean.dirty_range (dirty_id) ON DELETE CASCADE,
    family          text NOT NULL,
    timeframe       text NOT NULL,
    build_id        text NOT NULL REFERENCES fb.build (build_id),
    consumed_at     timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (dirty_id, family, timeframe),
    FOREIGN KEY (family, timeframe) REFERENCES fb.family_timeframe (family, timeframe)
