-- A family is one piece of logic (e.g. leadership). It is defined once and instantiated per
-- timeframe in fb.family_timeframe; each instance is its own table <tier>.<family>_<timeframe>.
CREATE TABLE fb.family (
    family              text PRIMARY KEY,
    tier                text NOT NULL CHECK (tier IN ('ind','feat','sig')),
                        -- ind:  single-series indicators; read clean bars only (SMA, RSI, ATR, rolling highs)
                        -- feat: features; read bars + indicators + features + reference data (leadership, regime)
                        -- sig:  stateful decisions; read anything below (watchlist, AIF arming)
    grain               text NOT NULL CHECK (grain IN ('listing','cluster','industry')),
    engine              text NOT NULL CHECK (engine IN ('pandas','sql','fsm')),
    stateful            boolean NOT NULL,          -- next bar needs the previous row (EMA, Wilder, FSM, all-time high)
    checkpoint_every    text NOT NULL DEFAULT 'none' CHECK (checkpoint_every IN ('none','month')),
                                                   -- 'month': hidden state not in the output row → fb.state_checkpoint
    cross_section_scope text NOT NULL CHECK (cross_section_scope IN ('none','industry','universe')),
    scale_invariant     boolean NOT NULL,          -- unchanged when a listing's whole history is rescaled
    asset_classes       text[] NOT NULL DEFAULT '{equity}',
    managed_ddl         boolean NOT NULL DEFAULT true,  -- true: tables are generated by fb.create_family_table
    owner_process       text NOT NULL,
    depends_on          text[] NOT NULL DEFAULT '{}',
    description         text NOT NULL,
    CHECK (tier <> 'ind' OR cross_section_scope = 'none'),
    CHECK (grain = 'listing' OR NOT managed_ddl)
);

-- Tier rule: ind may depend only on ind; feat on ind/feat; sig on anything. Checked on write.
CREATE FUNCTION fb.check_family_tiers() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    rank_of CONSTANT jsonb := '{"ind":1,"feat":2,"sig":3}';
    bad text;
BEGIN
    SELECT string_agg(d.family || ' (' || d.tier || ')', ', ') INTO bad
    FROM unnest(NEW.depends_on) dep
    JOIN fb.family d ON d.family = dep
    WHERE (rank_of ->> d.tier)::int > (rank_of ->> NEW.tier)::int;
    IF bad IS NOT NULL THEN
        RAISE EXCEPTION 'family % (tier %) cannot depend on higher tier: %', NEW.family, NEW.tier, bad;
    END IF;
    IF EXISTS (SELECT 1 FROM unnest(NEW.depends_on) dep WHERE NOT EXISTS (SELECT 1 FROM fb.family WHERE family = dep)
               AND dep <> NEW.family) THEN
        RAISE EXCEPTION 'family % depends on an unregistered family', NEW.family;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER family_tier_order BEFORE INSERT OR UPDATE ON fb.family
    FOR EACH ROW EXECUTE FUNCTION fb.check_family_tiers();

CREATE TABLE fb.family_timeframe (
    family          text NOT NULL REFERENCES fb.family (family),
    timeframe       text NOT NULL CHECK (timeframe IN ('1d','1w','1mo')),
    schema_name     text NOT NULL CHECK (schema_name IN ('ind','feat','sig')),
    table_name      text NOT NULL,                 -- '<family>_<timeframe>'
    warmup_bars     integer NOT NULL CHECK (warmup_bars >= 0),   -- in bars of this timeframe
    status          text NOT NULL DEFAULT 'active' CHECK (status IN ('draft','active','retired')),
    PRIMARY KEY (family, timeframe),
    UNIQUE (schema_name, table_name),
    CHECK (table_name = family || '_' || timeframe)
);

CREATE TABLE fb.feature_def (
    feature         text NOT NULL,                 -- 'rsi_close_14'
    timeframe       text NOT NULL,
    version         smallint NOT NULL CHECK (version >= 1),
    family          text NOT NULL,
    ordinal         smallint NOT NULL,             -- column order in the generated table
    column_name     text NOT NULL,
    dtype           text NOT NULL CHECK (dtype IN ('double precision','real','integer','smallint','bigint',
                                                   'boolean','date','text','jsonb')),
    allowed_values  text[],                        -- becomes CHECK (col = ANY (...))
    value_min       double precision,              -- becomes CHECK (col >= min)
    value_max       double precision,              -- becomes CHECK (col <= max)
    params          jsonb NOT NULL DEFAULT '{}'::jsonb,  -- windows etc. (replaces config/nse_*.json)
    -- the feature contract: how the value behaves, recorded once and checked by ops.dq_check
    window_unit     text CHECK (window_unit IN ('bars','sessions','calendar','expanding','cross_section','none')),
    window_length   integer CHECK (window_length > 0),
    min_bars        integer CHECK (min_bars >= 0),  -- NULL until this many bars exist
    null_policy     text CHECK (null_policy IN ('null_until_full','partial_window','fill_value','zero_on_missing')),
    gap_policy      text CHECK (gap_policy IN ('skip_missing','null_if_any_missing','count_as_missing','carry_forward')),
    uses_future     boolean NOT NULL DEFAULT false, -- true = value depends on later bars; never usable as-of
    definition      text,                           -- plain-language meaning
    formula         text,                           -- exact calculation
    inputs          text[] NOT NULL DEFAULT '{}',
    legacy_source   text,                          -- e.g. 'nse.sma_close_21'
    description     text,
    status          text NOT NULL DEFAULT 'active' CHECK (status IN ('draft','active','deprecated')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (family, timeframe, feature, version),     -- a feature is named within its family
    FOREIGN KEY (family, timeframe) REFERENCES fb.family_timeframe (family, timeframe),
    UNIQUE (family, timeframe, column_name, version),
    CHECK (allowed_values IS NULL OR dtype = 'text'),
    CHECK (value_min IS NULL OR value_max IS NULL OR value_min <= value_max)
);
CREATE UNIQUE INDEX feature_def_one_active ON fb.feature_def (family, timeframe, feature) WHERE status = 'active';

-- Features that read later bars. The publish step refuses to expose these to the app as as-of
-- signals, and backtests must exclude them.
CREATE VIEW fb.lookahead_features AS
SELECT family, timeframe, feature, version, definition
FROM fb.feature_def WHERE uses_future AND status <> 'deprecated';

CREATE TABLE fb.build (
    build_id        text PRIMARY KEY,              -- '<UTC minute>/<venue>/<family>_<timeframe>'
    family          text NOT NULL,
    timeframe       text NOT NULL,
    venue_id        smallint NOT NULL REFERENCES ref.venue (venue_id),
    run_id          uuid NOT NULL REFERENCES public.run_log (run_id),
    kind            text NOT NULL CHECK (kind IN ('incremental','dirty_rebuild','full','parity_shadow')),
    span_start      date NOT NULL,
    span_end        date NOT NULL,
    listing_scope   integer[],                     -- NULL = every listing in scope
    rows_written    bigint NOT NULL,
    started_at      timestamptz,
    dq_passed       boolean NOT NULL,
    built_at        timestamptz NOT NULL,
    published_at    timestamptz,
    FOREIGN KEY (family, timeframe) REFERENCES fb.family_timeframe (family, timeframe),
    CHECK (span_end >= span_start)
);
CREATE INDEX build_published_idx ON fb.build (family, timeframe, venue_id, published_at DESC) WHERE published_at IS NOT NULL;

CREATE TABLE fb.build_feature (
