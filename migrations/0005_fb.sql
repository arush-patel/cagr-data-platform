-- Month-end snapshots of hidden FSM state (families with checkpoint_every = 'month').
-- A recompute from date d loads the newest checkpoint before d and replays forward.
CREATE TABLE fb.state_checkpoint (
    family          text NOT NULL,
    timeframe       text NOT NULL,
    entity_kind     text NOT NULL CHECK (entity_kind IN ('listing','cluster','industry')),
    entity_id       integer NOT NULL,              -- listing_id, industry_id*1000+cluster_no, or industry_id
    bar_date        date NOT NULL,
    state           jsonb NOT NULL,
    build_id        text NOT NULL REFERENCES fb.build (build_id),
    PRIMARY KEY (family, timeframe, entity_kind, entity_id, bar_date),
    FOREIGN KEY (family, timeframe) REFERENCES fb.family_timeframe (family, timeframe)
);

-- What each family instance must recompute for every unconsumed dirty range.
--   scope none      → that listing only, from from_date (its own levels changed)
--   scope industry  → every listing in that listing's industry, or in d.industry_id when the fact names one
--   scope universe  → every listing on the venue
--   cross-sectional AND scale_invariant AND an anchor date → only from the anchor date
--   stateful        → resume from the previous row, or the newest checkpoint before recompute_from
--   1w / 1mo        → the build rounds recompute_from down to the start of its period
CREATE VIEW fb.dirty_plan AS
SELECT d.dirty_id,
       ft.family,
       ft.timeframe,
       f.tier,
       f.cross_section_scope                                   AS scope,
       d.venue_id,
       CASE WHEN f.cross_section_scope = 'none' THEN d.listing_id END AS listing_id,
       CASE WHEN f.cross_section_scope = 'industry' THEN coalesce(d.industry_id, ic.industry_id) END AS industry_id,
       CASE WHEN f.cross_section_scope <> 'none' AND f.scale_invariant AND d.anchor_date IS NOT NULL
            THEN d.anchor_date ELSE d.from_date END            AS recompute_from,
       d.to_date                                               AS recompute_to,
       f.stateful,
       f.checkpoint_every,
       d.reason
FROM clean.dirty_range d
CROSS JOIN fb.family_timeframe ft
JOIN fb.family f ON f.family = ft.family
LEFT JOIN ref.listing l ON l.listing_id = d.listing_id
LEFT JOIN ref.instrument i ON i.instrument_id = l.instrument_id
LEFT JOIN ref.universe u ON u.venue_id = d.venue_id
LEFT JOIN ref.instrument_classification ic
       ON ic.instrument_id = l.instrument_id AND ic.scheme_id = u.scheme_id AND ic.valid_to IS NULL AND ic.superseded_at IS NULL
WHERE ft.status = 'active'
  AND (i.asset_class IS NULL OR i.asset_class = ANY (f.asset_classes))
  AND NOT (d.industry_id IS NOT NULL AND f.cross_section_scope = 'none')   -- a reclassification leaves bars alone
  AND NOT EXISTS (SELECT 1 FROM fb.dirty_consumed c
                  WHERE c.dirty_id = d.dirty_id AND c.family = ft.family AND c.timeframe = ft.timeframe);

