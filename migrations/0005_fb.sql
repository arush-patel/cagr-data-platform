-- Creates <tier>.<family>_<timeframe> from fb.feature_def. Daily tables are partitioned by year.
-- Adding weekly leadership = register family_timeframe + feature_def rows, call this, run a build.
CREATE FUNCTION fb.create_family_table(p_family text, p_timeframe text) RETURNS text
LANGUAGE plpgsql AS $$
DECLARE
    f     fb.family;
    ft    fb.family_timeframe;
    r     record;
    cols  text := '';
    fq    text;
BEGIN
    SELECT * INTO f FROM fb.family WHERE family = p_family;
    IF NOT FOUND THEN RAISE EXCEPTION 'unknown family %', p_family; END IF;
    IF NOT f.managed_ddl THEN RAISE EXCEPTION 'family % has hand-written DDL', p_family; END IF;
    SELECT * INTO ft FROM fb.family_timeframe WHERE family = p_family AND timeframe = p_timeframe;
    IF NOT FOUND THEN RAISE EXCEPTION 'family % has no % timeframe registered', p_family, p_timeframe; END IF;

    FOR r IN SELECT column_name, dtype, allowed_values, value_min, value_max
             FROM fb.feature_def
             WHERE family = p_family AND timeframe = p_timeframe AND status <> 'deprecated'
             ORDER BY ordinal LOOP
        cols := cols || format(E',\n    %I %s', r.column_name, r.dtype);
        IF r.allowed_values IS NOT NULL THEN
            cols := cols || format(' CHECK (%I = ANY (%L::text[]))', r.column_name, r.allowed_values);
        END IF;
        IF r.value_min IS NOT NULL THEN cols := cols || format(' CHECK (%I >= %s)', r.column_name, r.value_min); END IF;
        IF r.value_max IS NOT NULL THEN cols := cols || format(' CHECK (%I <= %s)', r.column_name, r.value_max); END IF;
    END LOOP;
    IF cols = '' THEN RAISE EXCEPTION 'no features registered for %_%', p_family, p_timeframe; END IF;

    fq := format('%I.%I', ft.schema_name, ft.table_name);
    EXECUTE format(E'CREATE TABLE %s (\n    bar_date date NOT NULL,\n    listing_id integer NOT NULL%s,\n    PRIMARY KEY (bar_date, listing_id)\n)%s',
                   fq, cols, CASE WHEN p_timeframe = '1d' THEN ' PARTITION BY RANGE (bar_date)' ELSE '' END);
    EXECUTE format('CREATE INDEX %I ON %s (listing_id, bar_date)', ft.table_name || '_listing_idx', fq);
    IF p_timeframe = '1d' THEN
        PERFORM ops.create_year_partitions(fq::regclass, 2010, 2030);
    END IF;
    EXECUTE format('COMMENT ON TABLE %s IS %L', fq, f.description);
    RETURN fq;
END $$;

-- Adds columns for newly registered features to an existing generated table (no rewrite:
-- ADD COLUMN without a default is metadata-only). The next build fills them.
CREATE FUNCTION fb.add_feature_columns(p_family text, p_timeframe text) RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    ft  fb.family_timeframe;
    r   record;
    n   integer := 0;
BEGIN
    SELECT * INTO ft FROM fb.family_timeframe WHERE family = p_family AND timeframe = p_timeframe;
    IF NOT FOUND THEN RAISE EXCEPTION 'family % has no % timeframe registered', p_family, p_timeframe; END IF;
    FOR r IN SELECT d.column_name, d.dtype FROM fb.feature_def d
             WHERE d.family = p_family AND d.timeframe = p_timeframe AND d.status <> 'deprecated'
               AND NOT EXISTS (SELECT 1 FROM information_schema.columns c
                               WHERE c.table_schema = ft.schema_name AND c.table_name = ft.table_name
                                 AND c.column_name = d.column_name)
             ORDER BY d.ordinal LOOP
        EXECUTE format('ALTER TABLE %I.%I ADD COLUMN %I %s', ft.schema_name, ft.table_name, r.column_name, r.dtype);
        n := n + 1;
    END LOOP;
    RETURN n;
END $$;

-- ---------------------------------------------------------------------------------------------
-- Feature lanes. Experimental features live only in the lake and expire unless used; production
-- features are reviewed code or formulas, computed nightly into Postgres and the lake. Several
-- versions of one feature may be active at once (a strategy version keeps reading the one it pinned).
-- ---------------------------------------------------------------------------------------------
ALTER TABLE fb.feature_def
    ADD COLUMN lane         text NOT NULL DEFAULT 'production' CHECK (lane IN ('experimental','production')),
    ADD COLUMN owner        text,
    ADD COLUMN code_ref     jsonb,          -- {"repo":"cagrmeister-lab","path":"features/breakout.py","function":"range_contraction","commit":"9f3a2c1"}
    ADD COLUMN expression   text,           -- a formula feature: the formula itself, evaluated by the engine
    ADD COLUMN storage      text NOT NULL DEFAULT 'pg_and_lake' CHECK (storage IN ('lake','pg_and_lake')),
    ADD COLUMN refresh      text NOT NULL DEFAULT 'nightly' CHECK (refresh IN ('nightly','manual')),
    ADD COLUMN is_current   boolean NOT NULL DEFAULT false,   -- the version a bare name resolves to
    ADD COLUMN last_used_at timestamptz,
    ADD COLUMN expires_at   timestamptz;    -- experimental only: archived after this unless pinned or used
ALTER TABLE fb.feature_def DROP CONSTRAINT feature_def_status_check,
    ADD CONSTRAINT feature_def_status_check CHECK (status IN ('draft','active','deprecated','archived')),
    ADD CONSTRAINT feature_def_lane_storage_check
        CHECK (lane = 'production' OR (storage = 'lake' AND expires_at IS NOT NULL)),
    ADD CONSTRAINT feature_def_source_check     -- an experimental feature says where its code or formula is
        CHECK (lane = 'production' OR status = 'draft' OR code_ref IS NOT NULL OR expression IS NOT NULL),
    ADD CONSTRAINT feature_def_reviewed_check
        CHECK (lane = 'experimental' OR status = 'draft' OR code_ref IS NULL OR code_ref ? 'commit');
UPDATE fb.feature_def SET is_current = true WHERE status = 'active';
DROP INDEX fb.feature_def_one_active;
CREATE UNIQUE INDEX feature_def_one_current ON fb.feature_def (family, timeframe, feature) WHERE is_current;
-- each active production version is its own column in the family table (v2 gets a new column name)
CREATE UNIQUE INDEX feature_def_column_once ON fb.feature_def (family, timeframe, column_name)
    WHERE lane = 'production' AND status = 'active';

ALTER TABLE fb.family DROP CONSTRAINT family_engine_check,
    ADD CONSTRAINT family_engine_check CHECK (engine IN ('pandas','polars','sql','fsm','formula','model'));

